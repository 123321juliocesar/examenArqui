import express from 'express';
import cors from 'cors';
import authRoutes from './routes/auth.routes.js';
import productRoutes from './routes/productos.routes.js';
import orderRoutes from './routes/pedidos.routes.js';
import purchaseRoutes from './routes/reposiciones.routes.js';
import stockRoutes from './routes/inventario.routes.js';
import { SaludController } from './controllers/SaludController.js';
import { wrap } from './controllers/wrap.js';
import { errorHandler,notFoundRoute } from './middlewares/errorHandler.js';
export const app=express();
app.disable('x-powered-by');
const allowed=(process.env.CLIENT_ORIGIN||'http://localhost:5173').split(',').map(s=>s.trim());
app.use(cors({origin(origin,callback){if(!origin||allowed.includes(origin))return callback(null,true);return callback(new Error('Origen CORS no permitido'));}}));
app.use(express.json({limit:'100kb'}));
app.get('/api/salud',wrap(SaludController.check));
app.use('/api/auth',authRoutes);
app.use('/api/productos',productRoutes);
app.use('/api/pedidos',orderRoutes);
app.use('/api/reposiciones',purchaseRoutes);
app.use('/api/inventario',stockRoutes);
app.use(notFoundRoute);
app.use(errorHandler);
